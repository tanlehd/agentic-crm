CREATE TABLE channel_ingress_touchpoint (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  command_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  receipt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  connection_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  contact_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  identity_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  binding_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_message_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  evidence JSON NOT NULL,
  state VARCHAR(16) NOT NULL,
  conversation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  message_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  terminal_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  PRIMARY KEY (tenant_id,id),
  UNIQUE KEY uq_channel_touchpoint_command (tenant_id,command_id),
  KEY ix_channel_touchpoint_recovery (tenant_id,connection_id,state,id),
  KEY ix_channel_touchpoint_conversation (tenant_id,conversation_id,id),
  CONSTRAINT ck_channel_touchpoint_tenant CHECK (tenant_id <> '01900000-0000-7000-8000-000000000001' AND tenant_id <> '00000000-0000-0000-0000-000000000000' AND tenant_id <> ''),
  CONSTRAINT ck_channel_touchpoint_version CHECK (version >= 1),
  CONSTRAINT ck_channel_touchpoint_evidence CHECK (JSON_TYPE(evidence)='OBJECT'),
  CONSTRAINT ck_channel_touchpoint_state CHECK (state IN ('prepared','bound','discarded','cancelled')),
  CONSTRAINT ck_channel_touchpoint_terminal CHECK ((state='prepared' AND terminal_digest IS NULL) OR (state<>'prepared' AND terminal_digest IS NOT NULL)),
  CONSTRAINT ck_channel_touchpoint_effect CHECK ((state='bound' AND conversation_id IS NOT NULL AND message_id IS NOT NULL) OR (state<>'bound' AND conversation_id IS NULL AND message_id IS NULL AND session_id IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='CRM Connector; business; staged referral evidence and terminal Chat binding';
