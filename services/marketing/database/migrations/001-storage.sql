-- Marketing database v1. Immutable after application. No cross-service references.
CREATE TABLE marketing_account (
  tenant_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider_node_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  external_account_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
  name VARCHAR(255) NULL,
  account_status_code BIGINT UNSIGNED NULL,
  disable_reason_code BIGINT UNSIGNED NULL,
  currency VARCHAR(255) NULL,
  provider_timezone_id BIGINT UNSIGNED NULL,
  timezone_name VARCHAR(255) NULL,
  observed_utc_offset_hours DECIMAL(6,3) NULL,
  business_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
  spend_cap_raw DECIMAL(30,0) NULL,
  provider VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'meta' CHECK (provider='meta'),
  version BIGINT UNSIGNED NOT NULL DEFAULT 1 CHECK (version>=1),
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  last_seen_at DATETIME(6) NOT NULL,
  availability VARCHAR(32) NOT NULL CHECK (availability IN ('available','restricted','unavailable','provider_deleted')),
  field_coverage JSON NOT NULL CHECK (JSON_STORAGE_SIZE(field_coverage)<=1048576),
  latest_observation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  PRIMARY KEY (tenant_id,id),
  CHECK (tenant_id REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' AND tenant_id NOT IN ('01900000-0000-7000-8000-000000000001','00000000-0000-0000-0000-000000000000')),
  UNIQUE (tenant_id,provider_node_id),
  UNIQUE (tenant_id,external_account_id),
  INDEX (tenant_id,updated_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='Marketing owned account; tenant scoped';

